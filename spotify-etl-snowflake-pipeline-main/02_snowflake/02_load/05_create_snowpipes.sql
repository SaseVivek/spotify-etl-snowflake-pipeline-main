-- Purpose: Automate the COPY INTO step for each table using Snowpipe.
-- Each pipe watches its corresponding stage and auto-loads new files as they arrive.

USE DATABASE MUSIC_CATALOG;
USE SCHEMA CATALOG_DATA;

-- Pipe for artists
CREATE OR REPLACE PIPE ARTISTS_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO ARTISTS
FROM @ARTISTS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT);

-- Pipe for albums
CREATE OR REPLACE PIPE ALBUMS_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO ALBUMS
FROM @ALBUMS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT);

-- Pipe for tracks
CREATE OR REPLACE PIPE TRACKS_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO TRACKS
FROM @TRACKS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT);

SHOW PIPES;

SELECT COUNT(*) FROM ARTISTS;