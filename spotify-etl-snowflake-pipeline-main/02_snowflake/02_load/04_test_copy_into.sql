-- Purpose: Load all 3 tables from their respective S3 stages,
-- then validate row counts and sample data for each.

USE DATABASE MUSIC_CATALOG;
USE SCHEMA CATALOG_DATA;


-- 1. ARTISTS

COPY INTO ARTISTS
FROM @ARTISTS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'CONTINUE';

SELECT * FROM ARTISTS LIMIT 10;
SELECT COUNT(*) AS artists_row_count FROM ARTISTS;



-- 2. ALBUMS

COPY INTO ALBUMS
FROM @ALBUMS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'CONTINUE';

SELECT * FROM ALBUMS LIMIT 10;
SELECT COUNT(*) AS albums_row_count FROM ALBUMS;



-- 3. TRACKS

COPY INTO TRACKS
FROM @TRACKS_STAGE
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'CONTINUE';

SELECT * FROM TRACKS LIMIT 10;
SELECT COUNT(*) AS tracks_row_count FROM TRACKS;